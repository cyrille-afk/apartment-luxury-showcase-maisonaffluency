/** Tokens are opaque: Meta, not a guessed alphabet or length, validates them. */
export function parseMetaTokenInput(value: unknown): { token: string; error?: string } {
  if (typeof value !== "string" || !value.trim()) {
    return { token: "", error: "Paste the access token generated by Meta's Graph API Explorer." };
  }
  const token = value.trim();
  if (/^https?:\/\//i.test(token)) {
    return { token: "", error: "This is a URL, not an access token. Copy only the Access Token value from Meta's Graph API Explorer." };
  }
  if (/\s/.test(token) || /^[\[{]/.test(token) || /^bearer\b/i.test(token) || token.length > 8192) {
    return { token: "", error: "Paste only the access token, without a Bearer prefix, spaces, or a copied response." };
  }
  return { token };
}