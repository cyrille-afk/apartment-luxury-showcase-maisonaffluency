import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { afterEach, expect, it, vi } from "vitest";
import ResidenceVisualizationDialog from "./ResidenceVisualizationDialog";
const mocks = vi.hoisted(() => ({ load: vi.fn(), generate: vi.fn() }));
vi.mock("@/lib/viewingRoom.functions", () => ({ getResidenceVisualizationShells: mocks.load, generateResidenceVisualization: mocks.generate }));
vi.mock("@tanstack/react-start", () => ({ useServerFn: (fn: unknown) => fn }));
afterEach(() => { cleanup(); vi.resetAllMocks(); });
it("stages once on opening and attaches only the generated view for the current collection", async () => {
  mocks.load.mockResolvedValue([{ label:"Living Room View", url:"https://example.com/shell.jpg" },{label:"Bay Windows",url:"https://example.com/bay.jpg"}]);
  mocks.generate.mockResolvedValue({ id:"render-one",url:"https://example.com/render.jpg" });
  const attach = vi.fn();
  const choices = [{slot_id:"slot",product_id:"selected-piece",finish_key:"chosen-finish"}];
  const client = new QueryClient({ defaultOptions:{queries:{retry:false}} });
  const props = { open:true,onOpenChange:vi.fn(),token:"room",packageId:"package",residence:"Bayfront",choices,selectionKey:"original-selection",onAttach:attach };
  const ui = (key: string) => <QueryClientProvider client={client}><ResidenceVisualizationDialog {...props} selectionKey={key} /></QueryClientProvider>;
  const mounted = render(ui("original-selection"));
  await screen.findByRole("button",{name:"Attach to Final Proposal PDF"});
  expect(mocks.generate).toHaveBeenCalledTimes(1);
  expect(mocks.generate).toHaveBeenCalledWith({data:{token:"room",packageId:"package",shellUrl:"https://example.com/shell.jpg",choices}});
  fireEvent.click(screen.getByRole("button",{name:"Attach to Final Proposal PDF"}));
  expect(attach).toHaveBeenCalledWith({id:"render-one",url:"https://example.com/render.jpg",selectionKey:"original-selection"});
  mounted.rerender(ui("changed-finishes"));
  await waitFor(() => expect(screen.queryByRole("button",{name:"Attach to Final Proposal PDF"})).not.toBeInTheDocument());
  const tab=screen.getByRole("tab",{name:"Bay Windows"});fireEvent.mouseDown(tab,{button:0,ctrlKey:false});fireEvent.click(tab);
  fireEvent.click(screen.getByRole("button",{name:"Generate View"}));
  await waitFor(() => expect(mocks.generate).toHaveBeenCalledTimes(2));
  expect(mocks.generate.mock.calls[1]?.[0]?.data.shellUrl).toBe("https://example.com/bay.jpg");
});